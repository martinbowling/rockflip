text+='void rf_art_water(UBYTE frame) BANKED {VBK_REG=1;set_bkg_data(80,16,frame?rf_water_1:rf_water_0);VBK_REG=0;}\n'
text+='void rf_art_tint(UBYTE phase) BANKED {UBYTE i;UWORD v,c[4];for(i=0;i<4;i++){v=((UWORD*)BkgPalette)[20+i];c[i]=phase==2?RGB((v&31)*3/4,((v>>5)&31)*3/4,((v>>10)&31)*3/4+3):v;}c[0]=((UWORD*)BkgPalette)[0];set_bkg_palette(5,1,c);}'
text+='void rf_art_backdrop(UWORD room,UBYTE phase) BANKED {if(rf_art_map(room,phase,1))return;VBK_REG=0;'
for room,(tiles,mapping) in enumerate(backdrops):
    text+=f'if(room=={room}){{set_bkg_data(96,{len(tiles)},rf_backdrop_tiles_{room});set_bkg_tiles(2,4,16,8,rf_backdrop_map_{room});VBK_REG=1;set_bkg_tiles(2,4,16,8,rf_backdrop_attrs_{room});}}'
text+='VBK_REG=0;}\n'
