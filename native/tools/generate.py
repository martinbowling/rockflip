text+='void rf_art_load(void) BANKED {VBK_REG=0;set_bkg_data(0,96,rf_font);VBK_REG=1;set_bkg_data(0,136,rf_terrain);VBK_REG=0;}\n'
text+='UBYTE rf_art_terrain_pal(UBYTE tile) BANKED {return rf_terrain_pal[tile];}\n'
