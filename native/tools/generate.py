def pixels(path):
    im=Image.open(ART/path)
    assert im.mode=='P' and set(im.get_flattened_data()) <= {0,1,2,3}
    return im

def tilebytes(im):
    out=[]
    for ty in range(0,im.height,8):
        for tx in range(0,im.width,8):
            for y in range(8):
                lo=hi=0
                for x in range(8):
                    v=im.getpixel((tx+x,ty+y))
                    lo|=(v&1)<<(7-x); hi|=((v>>1)&1)<<(7-x)
                out.extend([lo,hi])
    return out

def decl(name,values):
    return 'static const UBYTE '+name+'[]={'+','.join(map(str,values))+'};\n'
# Terrain tiles in fixed order with an explicit palette per metatile.
names=pal['terrain_runtime_order']
world=[]; slots=[]
for name in names:
    group=next(g for g,order in pal['sheet_order'].items() if g.startswith('tiles_') and name in order)
    k=pal['sheet_order'][group].index(name)
    world.extend(tilebytes(pixels(group+'.png').crop((16*k,0,16*k+16,16))))
    slots.append({'desert':0,'scrub':1,'granite':2,'forest':3,'creek':4,'camp':6}[group[6:]])
world.extend(tilebytes(pixels('tall_joshua_tree.png')))
world.extend(tilebytes(pixels('outcrop.png')))
world.extend(tilebytes(pixels('horizon.png')))
# Simple hand-built burrow and shelter use existing rock/trail tiles with labels.
